create table if not exists tenants (
  id bigint generated by default as identity primary key,
  codigo varchar(32) not null unique,
  nome varchar(120) not null,
  criado_em timestamptz not null default now()
);

create table if not exists professores (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references tenants(id),
  usuario varchar(80) not null,
  senha_hash varchar(255) not null,
  nome varchar(120) not null,
  unique(tenant_id, usuario)
);

create table if not exists alunos (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references tenants(id),
  nome varchar(120) not null,
  nome_norm varchar(120) not null,
  eh_dupla integer not null default 0,
  ativo integer not null default 1,
  criado_em timestamptz not null default now(),
  unique(tenant_id, nome_norm)
);

create table if not exists progresso (
  id bigint generated by default as identity primary key,
  aluno_id bigint not null references alunos(id),
  atividade_key varchar(20) not null,
  modulo_id integer not null,
  atividade_id integer not null,
  xp integer not null default 0,
  concluido integer not null default 1,
  concluido_em timestamptz not null default now(),
  unique(aluno_id, atividade_key)
);

create table if not exists tentativas (
  id bigint generated by default as identity primary key,
  aluno_id bigint not null references alunos(id),
  tenant_id bigint not null references tenants(id),
  modulo_id integer not null,
  atividade_id integer not null,
  atividade_key varchar(20) not null,
  skill varchar(80) default '',
  erros integer default 0,
  tempo_ms integer default 0,
  concluiu integer default 0,
  criado_em timestamptz not null default now()
);

create index if not exists idx_tentativas_aluno on tentativas(aluno_id);
create index if not exists idx_tentativas_mod on tentativas(tenant_id, modulo_id);
create index if not exists idx_tentativas_ativ on tentativas(tenant_id, atividade_key);
create index if not exists idx_progresso_aluno on progresso(aluno_id);

